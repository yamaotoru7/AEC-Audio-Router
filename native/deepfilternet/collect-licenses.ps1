#requires -Version 5
# Writes the license notices of every Rust crate linked into deepfilter.dll (libDF with the
# capi feature): name, version, declared license, and the license / notice files the crate
# ships. Called by build-deepfilternet.ps1 after a successful build.
param(
    [Parameter(Mandatory)] [string] $Source,      # DeepFilterNet checkout
    [Parameter(Mandatory)] [string] $Toolchain,
    [Parameter(Mandatory)] [string] $Output
)
$ErrorActionPreference = 'Stop'
$manifest = Join-Path $Source 'libDF/Cargo.toml'
$toolchainArg = "+$Toolchain"
$common = @('--locked', '--manifest-path', $manifest, '--no-default-features', '--features', 'capi')

# The crates actually linked: the normal (non-dev, non-build) dependency tree of this build.
$tree = & cargo $toolchainArg tree @common -e normal --prefix none --format '{p}'
if ($LASTEXITCODE -ne 0) { throw 'cargo tree failed.' }
$linked = @{}
foreach ($line in $tree) {
    if ($line -match '^(\S+) v(\S+)') { $linked["$($Matches[1]) $($Matches[2])"] = $true }
}

$json = & cargo $toolchainArg metadata @common --format-version 1
if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed.' }
$metadata = ($json -join "`n") | ConvertFrom-Json
$packages = $metadata.packages | Where-Object { $linked.ContainsKey("$($_.name) $($_.version)") } | Sort-Object name, version

$text = New-Object System.Text.StringBuilder
[void]$text.AppendLine('Rust crates linked into deepfilter.dll (DeepFilterNet libDF C API)')
[void]$text.AppendLine('Generated by native/deepfilternet/collect-licenses.ps1 from the pinned Cargo.lock.')
[void]$text.AppendLine('Where a crate offers a choice of licenses, it is used under the MIT license if that')
[void]$text.AppendLine('is among them. The license and notice files each crate ships follow its entry.')
foreach ($package in $packages) {
    $directory = Split-Path $package.manifest_path
    [void]$text.AppendLine()
    [void]$text.AppendLine(('=' * 78))
    [void]$text.AppendLine("$($package.name) $($package.version)")
    [void]$text.AppendLine("License: $($package.license)")
    if ($package.repository) { [void]$text.AppendLine("Source: $($package.repository)") }
    $files = Get-ChildItem -LiteralPath $directory -File |
        Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE|COPYRIGHT)' } | Sort-Object Name
    # With an MIT option, the MIT text (plus any NOTICE) is enough; skip the other license texts.
    if ($package.license -match '\bMIT\b') {
        $mit = $files | Where-Object { $_.Name -match 'MIT' }
        if ($mit) { $files = @($mit) + @($files | Where-Object { $_.Name -match '^NOTICE' }) }
    }
    if (-not $files) {
        [void]$text.AppendLine('(The crate ships no license file; the standard text of the license above applies.)')
    }
    foreach ($file in $files) {
        [void]$text.AppendLine()
        [void]$text.AppendLine("--- $($file.Name)")
        [void]$text.AppendLine((Get-Content -LiteralPath $file.FullName -Raw -Encoding UTF8).TrimEnd())
    }
}
[System.IO.File]::WriteAllText($Output, $text.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Host "deepfilter.dll crate licenses: $($packages.Count) crates -> $Output"
